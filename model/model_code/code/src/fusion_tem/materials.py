# material_properties.py
import numpy as np

# =============================================================================
# 304L 不锈钢 (Stainless Steel 304L)
# =============================================================================
d_ss304 = 6900.0  # 密度 (kg/m^3)

def rho_ss304(T):
    """304L不锈钢的电阻率 (Ω·m)"""
    return 4.769612E-7 + 8.670423E-10*T**1 - 1.750491E-13*T**2

def Cp_ss304(T):
    """304L不锈钢的比热容 (J/kg·K)"""
    if T < 14:
        return 4.803500341 - 1.973988429*T**1 + 0.4334445971*T**2 - 0.03143247449*T**3 + 8.324034101E-4*T**4
    elif 14 <= T <= 47:
        return -0.224966167 + 0.7605685233*T**1 - 0.04007507385*T**2 + 0.002181760559*T**3 - 1.836023786E-5*T**4
    elif 47 < T <= 128:
        return 8.996783641 - 2.900986708*T**1 + 0.1470793134*T**2 - 0.001254896884*T**3 + 3.414011375E-6*T**4
    else:
        return 270.2756399 - 1.210511323*T**1 + 0.02151566558*T**2 - 7.511842703E-5*T**3 + 8.13679775E-8*T**4

def k_ss304(T):
    """304L不锈钢的热导率 (W/m·K)"""
    if T > 1 and T < 80:
        return -0.03740870672 + 0.06460545903*T**1 + 0.003720603527*T**2 - 8.390066559E-5*T**3 + 6.00659387E-7*T**4
    elif 80 <= T <= 283:
        return -1.03044565 + 0.1813806606*T**1 - 0.001088656189*T**2 + 3.411681019E-6*T**3 - 3.988389145E-9*T**4
    else:
        return -1.25819152 + 0.1023944897*T**1 - 2.189547019E-4*T**2 + 2.312931248E-7*T**3 - 8.903936981E-11*T**4

# =============================================================================
# OFHC 铜 (OFHC Copper)
# =============================================================================
d_copper = 8960.0  # 密度 (kg/m^3)

def resistivity_Cu(T, RRR=100):
    """OFHC铜的电阻率 (Ω·m)，考虑RRR"""
    rho_300K = 1.7e-8
    rho_res = rho_300K / RRR
    rho_ph = 6.0e-11*T + 7.0e-15*T**2
    return rho_res + rho_ph

def thermal_conductivity_Cu(T, RRR=100):
    """OFHC铜的热导率 (W/m·K)"""
    if 1.0 <= T < 25.0:
        return (24.5294281 + 135.07956*T + 4.74198629*T**2 
                -0.37230238*T**3 + 0.00472043868*T**4)
    elif 25.0 <= T < 44.0:
        return (3951.81367 - 63.68*T + 0.0514285714*T**2)
    elif 44.0 <= T < 74.0:
        return (6320.26628 - 201.224234*T + 2.37445974*T**2 
                -0.00955454847*T**3)
    elif 74.0 <= T < 100.0:
        return (4754.89856 - 147.179286*T + 1.92236905*T**2 
                -0.0112928571*T**3 + 2.48809524e-5*T**4)
    elif 100.0 <= T < 250.0:
        return (825.898597 - 6.98666667*T + 0.0440666667*T**2 
                -1.25333333e-4*T**3 + 1.33333333e-7*T**4)
    elif 250.0 <= T <= 500.0:
        return (762.582657 - 5.70709974*T + 0.0364306908*T**2
                -1.20974465e-4*T**3 + 2.18735712e-7*T**4 
                -2.04832488e-10*T**5 + 7.77997189e-14*T**6)
    else:
        raise ValueError(f"T={T} K 超出有效区间 [1,500] K")